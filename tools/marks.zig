//! Writes the combining-mark tables of `tuppet png` as Zig source, from the
//! Unicode data that Ghostty's uucode dependency vendors; build.zig runs it
//! on the host:
//!
//!     marks UnicodeData.txt CompositionExclusions.txt DerivedCoreProperties.txt OUT
//!
//! OUT lists runs of code points with their canonical combining class and
//! whether they are marks to draw over a base (Mn and Me, less the default
//! ignorable ones), and the primary composites of canonical composition.

const std = @import("std");

const max_cp = 0x10FFFF;

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 5) fatal("usage: marks UnicodeData.txt CompositionExclusions.txt DerivedCoreProperties.txt OUT", .{});
    const cwd = std.Io.Dir.cwd();
    const data = try cwd.readFileAlloc(io, args[1], a, .limited(16 << 20));
    const exclusions = try cwd.readFileAlloc(io, args[2], a, .limited(1 << 20));
    const derived = try cwd.readFileAlloc(io, args[3], a, .limited(16 << 20));

    const ccc = try a.alloc(u8, max_cp + 1);
    @memset(ccc, 0);
    var mark: std.DynamicBitSetUnmanaged = try .initEmpty(a, max_cp + 1);
    var excluded: std.DynamicBitSetUnmanaged = try .initEmpty(a, max_cp + 1);
    const Decomposition = struct { cp: u21, first: u21, second: u21 };
    var pairs: std.ArrayList(Decomposition) = .empty;

    var lines = std.mem.splitScalar(u8, data, '\n');
    while (lines.next()) |line| {
        if (line.len == 0) continue;
        var fields = std.mem.splitScalar(u8, line, ';');
        const cp = try parseCp(fields.next().?);
        _ = fields.next(); // name
        const category = fields.next() orelse fatal("{s}: short line {s}", .{ args[1], line });
        ccc[cp] = try std.fmt.parseInt(u8, fields.next() orelse fatal("{s}: short line {s}", .{ args[1], line }), 10);
        if (std.mem.eql(u8, category, "Mn") or std.mem.eql(u8, category, "Me")) mark.set(cp);
        _ = fields.next(); // bidi class
        const decomposition = fields.next() orelse fatal("{s}: short line {s}", .{ args[1], line });
        // Compatibility mappings, tagged <...>, do not compose.
        if (decomposition.len == 0 or decomposition[0] == '<') continue;
        var parts = std.mem.tokenizeScalar(u8, decomposition, ' ');
        const first = try parseCp(parts.next().?);
        // Singletons never compose.
        const second = try parseCp(parts.next() orelse continue);
        if (parts.next() != null) fatal("{s}: a canonical mapping of more than two: {s}", .{ args[1], line });
        try pairs.append(a, .{ .cp = cp, .first = first, .second = second });
    }

    try forEachListed(exclusions, null, &excluded);
    var ignorable: std.DynamicBitSetUnmanaged = try .initEmpty(a, max_cp + 1);
    try forEachListed(derived, "Default_Ignorable_Code_Point", &ignorable);

    var out: std.Io.Writer.Allocating = .init(a);
    const w = &out.writer;
    try w.writeAll(
        \\//! Generated by tools/marks.zig from the Unicode data of uucode.
        \\
        \\/// Code points `first` to `last` share a canonical combining class;
        \\/// `mark` says whether they are marks drawn over their base.
        \\pub const Run = struct { first: u21, last: u21, ccc: u8, mark: bool };
        \\
        \\/// A primary composite: `first` then `second` compose to `composite`.
        \\pub const Pair = struct { first: u21, second: u21, composite: u21 };
        \\
        \\/// Ascending; code points in none have class 0 and are no marks.
        \\pub const runs = [_]Run{
        \\
    );
    var cp: u21 = 0;
    while (cp <= max_cp) {
        const is_mark = mark.isSet(cp) and !ignorable.isSet(cp);
        if (ccc[cp] == 0 and !is_mark) {
            cp += 1;
            continue;
        }
        var last = cp;
        while (last < max_cp and ccc[last + 1] == ccc[cp] and (mark.isSet(last + 1) and !ignorable.isSet(last + 1)) == is_mark) last += 1;
        try w.print("    .{{ .first = 0x{X}, .last = 0x{X}, .ccc = {d}, .mark = {} }},\n", .{ cp, last, ccc[cp], is_mark });
        if (last == max_cp) break;
        cp = last + 1;
    }
    try w.writeAll(
        \\};
        \\
        \\/// Ascending by `first`, then `second`.
        \\pub const pairs = [_]Pair{
        \\
    );
    std.mem.sortUnstable(Decomposition, pairs.items, {}, struct {
        fn less(_: void, x: Decomposition, y: Decomposition) bool {
            return if (x.first != y.first) x.first < y.first else x.second < y.second;
        }
    }.less);
    for (pairs.items) |p| {
        // Full composition exclusion: listed, or a non-starter decomposition.
        if (excluded.isSet(p.cp) or ccc[p.cp] != 0 or ccc[p.first] != 0) continue;
        try w.print("    .{{ .first = 0x{X}, .second = 0x{X}, .composite = 0x{X} }},\n", .{ p.first, p.second, p.cp });
    }
    try w.writeAll("};\n");
    try cwd.writeFile(io, .{ .sub_path = args[4], .data = out.written() });
}

/// Sets the code points and ranges a UCD property file lists, those with
/// `property` when it is given.
fn forEachListed(text: []const u8, property: ?[]const u8, set: *std.DynamicBitSetUnmanaged) !void {
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, raw[0 .. std.mem.indexOfScalar(u8, raw, '#') orelse raw.len], " \t\r");
        if (line.len == 0) continue;
        var fields = std.mem.splitScalar(u8, line, ';');
        const range = std.mem.trim(u8, fields.next().?, " \t");
        if (property) |name| {
            const value = std.mem.trim(u8, fields.next() orelse continue, " \t");
            if (!std.mem.eql(u8, value, name)) continue;
        }
        const dots = std.mem.indexOf(u8, range, "..");
        const first = try parseCp(if (dots) |d| range[0..d] else range);
        const last = if (dots) |d| try parseCp(range[d + 2 ..]) else first;
        set.setRangeValue(.{ .start = first, .end = @as(usize, last) + 1 }, true);
    }
}

fn parseCp(text: []const u8) !u21 {
    const cp = try std.fmt.parseInt(u21, std.mem.trim(u8, text, " \t"), 16);
    if (cp > max_cp) return error.Overflow;
    return cp;
}

fn fatal(comptime fmt: []const u8, args: anytype) noreturn {
    std.debug.print("marks: " ++ fmt ++ "\n", args);
    std.process.exit(1);
}
